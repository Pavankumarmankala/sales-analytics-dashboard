"""Generate the executive KPI summary.

Reads the cleaned sales_orders table from SQLite and writes a short
executive summary to ``outputs/kpi_summary.md``: headline KPIs, the best
and worst performing regions, and the discount-profitability finding
(profit margin for undiscounted orders vs heavily discounted orders).

Run after ``src/etl.py``:
    python src/kpi_summary.py
"""

import sqlite3
from pathlib import Path

import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parent.parent
DB_PATH = PROJECT_ROOT / "data" / "sales_analytics.db"
OUTPUT_PATH = PROJECT_ROOT / "outputs" / "kpi_summary.md"


def money(value: float) -> str:
    return f"${value:,.2f}"


def main() -> None:
    if not DB_PATH.exists():
        raise FileNotFoundError(
            f"{DB_PATH} not found — run `python src/etl.py` first."
        )

    with sqlite3.connect(DB_PATH) as conn:
        df = pd.read_sql_query("SELECT * FROM sales_orders", conn)

    total_revenue = df["revenue"].sum()
    total_orders = len(df)
    total_profit = df["profit"].sum()
    aov = total_revenue / total_orders
    margin = total_profit / total_revenue * 100
    unique_customers = df["customer_id"].nunique()

    region = (
        df.groupby("region")
        .agg(revenue=("revenue", "sum"), profit=("profit", "sum"),
             avg_discount=("discount", "mean"))
        .sort_values("revenue", ascending=False)
    )
    region["margin_pct"] = region["profit"] / region["revenue"] * 100
    best_region = region.index[0]
    worst_region = region.index[-1]
    region_gap = (
        (region.loc[best_region, "revenue"] - region.loc[worst_region, "revenue"])
        / total_revenue
        * 100
    )

    top_category = df.groupby("category")["revenue"].sum().idxmax()
    top_product = df.groupby("product")["revenue"].sum().idxmax()

    no_discount = df[df["discount"] == 0]
    heavy_discount = df[df["discount"] >= 0.20]
    margin_none = no_discount["profit"].sum() / no_discount["revenue"].sum() * 100
    margin_heavy = heavy_discount["profit"].sum() / heavy_discount["revenue"].sum() * 100

    lines = [
        "# Executive KPI Summary — Sales Analytics Dashboard",
        "",
        "Period: calendar year 2024 (synthetic dataset)  ",
        f"Generated by `src/kpi_summary.py` from {total_orders:,} cleaned orders.",
        "",
        "## Headline KPIs",
        "",
        f"- **Total revenue:** {money(total_revenue)}",
        f"- **Total orders:** {total_orders:,}",
        f"- **Total profit:** {money(total_profit)} ({margin:.1f}% margin)",
        f"- **Average order value:** {money(aov)}",
        f"- **Units sold:** {int(df['units'].sum()):,}",
        f"- **Distinct customers:** {unique_customers:,}",
        f"- **Average discount:** {df['discount'].mean() * 100:.1f}%",
        "",
        "## Regional performance",
        "",
        f"- **Best region:** {best_region} — {money(region.loc[best_region, 'revenue'])} "
        f"revenue, {region.loc[best_region, 'margin_pct']:.1f}% margin, "
        f"{region.loc[best_region, 'avg_discount'] * 100:.1f}% average discount.",
        f"- **Worst region:** {worst_region} — {money(region.loc[worst_region, 'revenue'])} "
        f"revenue, {region.loc[worst_region, 'margin_pct']:.1f}% margin, "
        f"{region.loc[worst_region, 'avg_discount'] * 100:.1f}% average discount.",
        f"- The gap between the best and worst region is "
        f"{money(region.loc[best_region, 'revenue'] - region.loc[worst_region, 'revenue'])} "
        f"({region_gap:.1f}% of total revenue) — a regional performance gap that "
        "tracks closely with how heavily each region discounts.",
        "",
        "## Category & product leaders",
        "",
        f"- **Top category:** {top_category} "
        f"({money(df.groupby('category')['revenue'].sum().max())} revenue).",
        f"- **Top product:** {top_product} "
        f"({money(df.groupby('product')['revenue'].sum().max())} revenue).",
        "",
        "## Discount–profitability finding",
        "",
        f"- Undiscounted orders run at a **{margin_none:.1f}% profit margin**.",
        f"- Orders discounted 20% or more run at a **{margin_heavy:.1f}% profit margin** "
        f"({len(heavy_discount):,} orders).",
        "- Discounting lifts order volume but compresses margin sharply: the "
        "heavily discounted band earns materially less profit per revenue "
        "dollar than undiscounted orders, so discount depth — not volume — "
        "is the main profitability lever in this dataset.",
        "",
    ]

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUTPUT_PATH}")
    print(f"Total revenue: {money(total_revenue)} | Orders: {total_orders:,} | AOV: {money(aov)}")


if __name__ == "__main__":
    main()
